def set_font(run, name=KO, size=10, bold=False, color=None, italic=False):
    run.font.name = name
    run.font.size = Pt(size)
    run.bold = bold
    run.italic = italic
    if color:
        run.font.color.rgb = RGBColor(*color)
    run._element.rPr.rFonts.set(qn("w:eastAsia"), name)


def style_doc(doc):
    st = doc.styles["Normal"]
    st.font.name = KO
    st.font.size = Pt(10)
    st.element.rPr.rFonts.set(qn("w:eastAsia"), KO)
    st.paragraph_format.line_spacing = 1.5
    st.paragraph_format.space_after = Pt(6)
    for i, sz in ((1, 15), (2, 12.5), (3, 11)):
        h = doc.styles[f"Heading {i}"]
        h.font.name = KO
        h.font.size = Pt(sz)
        h.font.bold = True
        h.font.color.rgb = RGBColor(0x15, 0x18, 0x1D)
        h.element.rPr.rFonts.set(qn("w:eastAsia"), KO)
        h.paragraph_format.space_before = Pt(16 if i == 1 else 12)
        h.paragraph_format.space_after = Pt(6)
    s = doc.sections[0]
    s.page_width, s.page_height = Cm(21.0), Cm(29.7)
    for a in ("top_margin", "bottom_margin"):
        setattr(s, a, Cm(2.3))
    for a in ("left_margin", "right_margin"):
        setattr(s, a, Cm(2.5))


def para(doc, text, size=10, bold=False, align=None, space_after=6, color=None):
    p = doc.add_paragraph()
    if align:
        p.alignment = align
    p.paragraph_format.space_after = Pt(space_after)
    set_font(p.add_run(text), size=size, bold=bold, color=color)
    return p


def bullets(doc, items):
    for it in items:
        p = doc.add_paragraph(style="List Bullet")
        p.paragraph_format.space_after = Pt(2)
        p.paragraph_format.line_spacing = 1.4
        set_font(p.add_run(it))


def figure(doc, filename, number, caption):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_before = Pt(10)
    p.paragraph_format.space_after = Pt(3)
    p.add_run().add_picture(str(FIG / filename), width=FIG_W)
    c = doc.add_paragraph()
    c.alignment = WD_ALIGN_PARAGRAPH.CENTER
    c.paragraph_format.space_after = Pt(14)
    c.paragraph_format.line_spacing = 1.3
    set_font(c.add_run(f"그림 {number}. "), size=9, bold=True, color=(0x45, 0x49, 0x4F))
    set_font(c.add_run(caption), size=9, color=(0x45, 0x49, 0x4F))


def table(doc, header, rows, widths=None):
    t = doc.add_table(rows=1, cols=len(header))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, h in enumerate(header):
        cell = t.rows[0].cells[i]
        cell.text = ""
        pr = cell.paragraphs[0]
        pr.paragraph_format.space_after = Pt(0)
        pr.paragraph_format.line_spacing = 1.2
        set_font(pr.add_run(h), size=9, bold=True)
        shd = OxmlElement("w:shd")
        shd.set(qn("w:fill"), "F2F1EE")
        cell._tc.get_or_add_tcPr().append(shd)
    for row in rows:
        cells = t.add_row().cells
        for i, v in enumerate(row):
            cells[i].text = ""
            pr = cells[i].paragraphs[0]
            pr.paragraph_format.space_after = Pt(0)
            pr.paragraph_format.line_spacing = 1.25
            set_font(pr.add_run(str(v)), size=9)
    if widths:
        for r in t.rows:
            for i, w in enumerate(widths):
                r.cells[i].width = Cm(w)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t


